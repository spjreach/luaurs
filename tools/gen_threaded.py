"""Generates crates/luau-rt/src/lvmthreaded.rs from `execute::<SS>` in
lvmexecute.rs: one handler function per opcode, chained with guaranteed tail
calls (`become`), so every handler ends in its own indirect jump (threaded
dispatch, like the C++ VM's computed goto).

Run after editing the interpreter loop:  python rust/tools/gen_threaded.py
"""
import os
import re
import sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "crates", "luau-rt", "src")
SRC = os.path.join(ROOT, "lvmexecute.rs")
OUT = os.path.join(ROOT, "lvmthreaded.rs")

lines = open(SRC, encoding="utf-8").read().split("\n")

start = next(i for i, l in enumerate(lines) if l.startswith("unsafe fn execute<const SS: bool>"))
end = next(i for i in range(start, len(lines)) if lines[i] == "}")
body = lines[start + 1:end]

prologue_end = next(i for i, l in enumerate(body) if l.strip() == "reload_frame!();")
prologue = [l for l in body[:prologue_end]
            if not re.match(r"\s*let mut (pc|cl|base|k): ", l)]

match_line = next(i for i, l in enumerate(body) if l.strip() == "match op {")

# collect arms: an arm starts at a line indented by exactly 12 spaces that is
# not a comment or closing brace, and runs until the next arm start / match end
arms = []
i = match_line + 1
depth_end = None
cur = None
while i < len(body):
    l = body[i]
    if l.startswith("        }") and not l.startswith("         "):
        # end of match
        break
    is_start = l.startswith("            ") and not l.startswith("             ") and l.strip() not in ("}", "{") \
        and not l.strip().startswith("//")
    if is_start:
        head = l.strip()
        j = i
        while not head.rstrip().endswith("{"):
            j += 1
            head += " " + body[j].strip()
        pat = head[: head.index("=>")].strip()
        cur = {"pat": pat, "lines": []}
        arms.append(cur)
        i = j + 1
        continue
    if cur is not None:
        cur["lines"].append(l)
    i += 1

DISPATCH = "become dispatch(L, pc, base, k);"
FRAME_DISPATCH = "become dispatch_frame(L, pc, base, k);"


LOOP_HEAD = re.compile(r"(^|[^\w])(while|for|loop)\b")


def fix(text, repl=None):
    """Replaces `continue;` that targets the interpreter loop (i.e. is not
    inside a nested `while`/`for`/`loop` body) with a tail dispatch (or
    `repl`)."""
    if repl is None:
        repl = DISPATCH
    out = []
    stack = []  # True for loop bodies
    stmt_start = 0
    i = 0
    n = len(text)
    while i < n:
        c = text[i]
        if text.startswith("//", i):
            j = text.find("\n", i)
            j = n if j < 0 else j
            out.append(text[i:j])
            i = j
            continue
        if c == "{":
            head = text[stmt_start:i]
            stack.append(LOOP_HEAD.search(head) is not None and "=>" not in head)
            out.append(c)
            i += 1
            stmt_start = i
            continue
        if c in "};":
            if c == "}" and stack:
                stack.pop()
            out.append(c)
            i += 1
            stmt_start = i
            continue
        if text.startswith("continue;", i) and (i == 0 or not (text[i - 1].isalnum() or text[i - 1] == "_")):
            out.append("continue;" if any(stack) else repl)
            i += len("continue;")
            stmt_start = i
            continue
        out.append(c)
        i += 1
    return "".join(out)


prologue_text = fix("\n".join(prologue))

out = []
out.append("// @generated by rust/tools/gen_threaded.py from `execute::<SS>` in lvmexecute.rs -- do not edit")
out.append("")
out.append("type Handler = unsafe extern \"sysv64-unwind\" fn(*mut lua_State, *const Instruction, StkId, *mut TValue);")
out.append("")
out.append("#[inline(always)]")
out.append("unsafe extern \"sysv64-unwind\" fn dispatch(L: *mut lua_State, pc: *const Instruction, base: StkId, k: *mut TValue) {")
out.append("    become HANDLERS[(*pc & 0xff) as usize](L, pc, base, k)")
out.append("}")
out.append("")
out.append("/// Threaded `luau_execute` (no single-stepping).")
out.append("pub(crate) unsafe fn execute_threaded(L: *mut lua_State) {")
out.append("    let ci = (*L).ci;")
out.append("    dispatch_frame(L, (*ci).savedpc, (*L).base, (*(*ci).p).k)")
out.append("}")
out.append("")

# hand-written fast paths (tools/threaded_fast.rs.in)
FAST = {}
fast_src = open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "threaded_fast.rs.in"), encoding="utf-8").read()
for sect in re.split(r"^// @fast ", fast_src, flags=re.M)[1:]:
    head, _, sbody = sect.partition("\n")
    for op in head.split():
        FAST[op] = sbody.rstrip()

table = []
for arm in arms:
    pat = arm["pat"]
    m = re.match(r"x @ \((.*)\)$", pat) or re.match(r"x @ (.*)$", pat)
    ops = [o.strip() for o in m.group(1).split("|")] if m else ([pat] if pat != "_" else ["_"])
    arm_lines = arm["lines"]
    # drop the arm's closing brace
    while arm_lines and (arm_lines[-1].strip() == "" or arm_lines[-1].strip().startswith("//")):
        arm_lines.pop()
    assert arm_lines[-1].strip() == "}", (pat, arm_lines[-1])
    arm_text = "\n".join(arm_lines[:-1])
    arm["raw"] = arm_text
    arm_text = arm_text.replace("ovr = orig as u32;", "become HANDLERS[(orig & 0xff) as usize](L, pc, base, k);")
    # frame-switching opcodes continue through dispatch_frame (native entry)
    frame_ops = {"OP_CALL", "OP_CALL_FB", "OP_FAST_P_CALL", "OP_RETURN"}
    is_frame = any(o.strip() in frame_ops for o in (m.group(1).split("|") if m else []))
    arm_text = fix(arm_text, FRAME_DISPATCH if is_frame else None)
    for op in ops:
        name = "h_DEFAULT" if op == "_" else "h_" + op
        opval = "op_of(*pc)" if op == "_" else op
        if op in FAST:
            slow_name = "s_" + op
            out.append("#[allow(unused_mut, unused_variables, unused_macros, unreachable_code, non_snake_case)]")
            out.append(f"unsafe extern \"sysv64-unwind\" fn {name}(L: *mut lua_State, pc: *const Instruction, base: StkId, k: *mut TValue) {{")
            out.append(f"    macro_rules! slow {{ () => {{ become {slow_name}(L, pc, base, k) }}; }}")
            out.append("    macro_rules! next { ($n:expr) => { become dispatch(L, pc.add($n), base, k) }; }")
            out.append("    macro_rules! jump { ($n:expr) => { become dispatch(L, pc.offset($n as isize), base, k) }; }")
            out.append("    let insn = *pc;")
            out.append(f"    let x: u8 = {opval};")
            out.append(FAST[op])
            out.append("}")
            out.append("")
            table.append((op, name))
            name = slow_name
            out.append("#[inline(never)]")
        out.append("#[allow(unused_mut, unused_variables, unused_macros, unused_assignments, unreachable_code, non_snake_case)]")
        out.append(f"unsafe extern \"sysv64-unwind\" fn {name}(L: *mut lua_State, mut pc: *const Instruction, mut base: StkId, mut k: *mut TValue) {{")
        out.append("    let mut cl: *mut Closure = clvalue((*(*L).ci).func);")
        out.append("    const SS: bool = false;")
        out.append(prologue_text)
        out.append("    let insn = *pc;")
        out.append(f"    let x: u8 = {opval};")
        out.append("    let op = x;")
        out.append("    {")
        out.append(arm_text)
        out.append("    }")
        out.append("    " + (FRAME_DISPATCH if op in ("OP_CALL", "OP_CALL_FB", "OP_FAST_P_CALL", "OP_RETURN") else DISPATCH))
        out.append("}")
        out.append("")
        if op != "_" and op not in FAST:
            table.append((op, name))

out.append("static HANDLERS: [Handler; 256] = {")
out.append("    let mut t: [Handler; 256] = [h_DEFAULT as Handler; 256];")
for op, name in table:
    out.append(f"    t[{op} as usize] = {name};")
out.append("    t")
out.append("};")
out.append("")

# Step functions for the native code generator: each executes one
# instruction and returns the next pc (null: leave the VM, like `return`).
# Opcodes that switch call frames are excluded (native code exits to the
# interpreter handler for them instead).
STEP = "return pc;"
step_prologue = fix("\n".join(prologue), STEP).replace("return;", "return std::ptr::null();")
step_table = []
for arm in arms:
    pat = arm["pat"]
    m = re.match(r"x @ \((.*)\)$", pat) or re.match(r"x @ (.*)$", pat)
    if not m:
        continue
    raw = arm["raw"]
    if re.search(r"(^|[^.\w])(cl|k) = |reload_frame!|ovr = |become ", raw):
        continue
    body = fix(raw, STEP).replace("return;", "return std::ptr::null();")
    for op in [o.strip() for o in m.group(1).split("|")]:
        out.append("#[allow(unused_mut, unused_variables, unused_macros, unused_assignments, unreachable_code, non_snake_case)]")
        out.append(f"pub(crate) unsafe extern \"sysv64-unwind\" fn st_{op}(L: *mut lua_State, mut pc: *const Instruction, mut base: StkId, mut k: *mut TValue) -> *const Instruction {{")
        out.append("    let mut cl: *mut Closure = clvalue((*(*L).ci).func);")
        out.append("    const SS: bool = false;")
        out.append(step_prologue)
        out.append("    let insn = *pc;")
        out.append(f"    let x: u8 = {op};")
        out.append("    let op = x;")
        out.append("    {")
        out.append(body)
        out.append("    }")
        out.append("    " + STEP)
        out.append("}")
        out.append("")
        step_table.append((op, f"st_{op}"))

out.append("pub(crate) type StepFn = unsafe extern \"sysv64-unwind\" fn(*mut lua_State, *const Instruction, StkId, *mut TValue) -> *const Instruction;")
out.append("/// Single-instruction steps (native code fallback); None: exit to the interpreter.")
out.append("pub(crate) static STEPS: [Option<StepFn>; 256] = {")
out.append("    let mut t: [Option<StepFn>; 256] = [None; 256];")
for op, name in step_table:
    out.append(f"    t[{op} as usize] = Some({name});")
out.append("    t")
out.append("};")
out.append("")
out.append("/// Address of the interpreter handler for `op` (native code exits jump there).")
out.append("pub(crate) fn handler_address(op: u8) -> usize {")
out.append("    HANDLERS[op as usize] as usize")
out.append("}")
out.append("")

open(OUT, "w", encoding="utf-8", newline="\n").write("\n".join(out))
print(f"{len(arms)} arms, {len(table)} handlers, {len(step_table)} steps -> {OUT}")
